"""HubSpot Leads API v1 client module for lead management, search, and lifecycle operations.

This module provides the LeadsClient class for interacting with HubSpot's
Leads API, supporting lead CRUD operations, search with flexible filtering
and sorting, webhook callback management, and lead lifecycle transitions
(close/open).

Key Exports:
    LeadsClient: Domain client for the Leads API, inheriting from
        BaseClient (hapi/base.py) for HTTP transport.
    list_to_dict_with_python_case_keys: Utility function that builds
        bidirectional lookup dicts mapping both camelCase and snake_case
        option name variants to their canonical camelCase API key.
    SORT_OPTIONS: List of valid sort field names for lead queries.
    TIME_PIVOT_OPTIONS: List of valid time pivot field names.
    SEARCH_OPTIONS: List of all recognized search/filter parameter names.
    BOOLEAN_SEARCH_OPTIONS: Set of search options that accept boolean values.

Architecture Note:
    The module implements a camelCase <-> snake_case option conversion
    layer that allows callers to use Pythonic snake_case parameter names
    (e.g., 'time_pivot', 'email_opt_out') which are transparently
    converted to the camelCase format expected by the HubSpot API
    (e.g., 'timePivot', 'emailOptOut'). This conversion is performed
    via pre-computed lookup dictionaries built at module load time by
    list_to_dict_with_python_case_keys.

See Also:
    hapi.base.BaseClient: Core HTTP engine that handles authentication,
        retry logic, and response parsing for all API calls.
    hapi.error.HapiError: Exception hierarchy for API error responses.
"""
