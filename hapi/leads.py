def list_to_dict_with_python_case_keys(list_):
    """Build a bidirectional lookup dict mapping camelCase and snake_case option names.

    For each option name string in the input list, this function creates
    dictionary entries that map both the original camelCase form and a
    generated snake_case variant back to the original camelCase key. This
    enables callers to use either naming convention when specifying API
    parameters.

    The conversion algorithm for each item:
        1. The original camelCase string maps to itself.
        2. If the string contains uppercase characters, a snake_case
           variant is generated by lowering the first character and
           inserting an underscore before each subsequent uppercase
           character (e.g., 'timePivot' -> 'time_pivot').
        3. The snake_case variant also maps to the original camelCase key.

    Args:
        list_ (list): A list of camelCase option name strings to index.
            Each string represents a valid API parameter name.

    Returns:
        dict: A dictionary where keys are both the original camelCase
            names and their generated snake_case equivalents, and values
            are always the original camelCase key string. For items
            that are already all-lowercase, only the identity mapping
            is included.
    """
    d = {}
    for item in list_:
        d[item] = item
        if item.lower() != item:
            python_variant = item[0].lower() + ''.join([c if c.lower()==c else '_%s'%c.lower() for c in item[1:]])
            d[python_variant] = item
    return d

